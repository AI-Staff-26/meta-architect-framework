// --check: lint and render in memory, compare with the files on disk, write nothing.

/** Every file under the directory, with its modification time and bytes: a command that writes nothing leaves it equal. */
function snapshot(dir: string): Map<string, string> {
  const out = new Map<string, string>();
  for (const rel of readdirSync(dir, { recursive: true, encoding: "utf8" }).sort()) {
    const path = join(dir, rel);
    const st = statSync(path);
    if (st.isFile()) out.set(rel, `${st.mtimeMs} ${readFileSync(path, "base64")}`);
  }
  return out;
}

/** The paths --check names, one per line: `<stale|missing|extra> <path relative to the blueprint>`. */
const named = (stdout: string) => stdout.split("\n").filter((line) => /^(stale|missing|extra) /.test(line));

test("--check after a build: everything matches, exit 0, nothing written", () => withDir((dir) => {
  assert.equal(run(dir).status, 0);
  const before = snapshot(dir);
  const r = run(dir, "--check");
  assert.equal(r.status, 0, r.stdout + r.stderr);
  assert.deepEqual(named(r.stdout), []);
  assert.match(r.stdout, /^\d+ files match src\/ · 0 errors, 0 warnings$/m);
  assert.deepEqual(snapshot(dir), before);
}));

