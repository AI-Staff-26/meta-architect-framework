// The command line, end to end: what it writes, what it refuses, and its exit codes.

const TOOL_DIR = join(import.meta.dirname, "..");
const BUILD = join(TOOL_DIR, "build.ts");

function runTool(build: string, ...args: string[]) {
  const r = spawnSync(process.execPath, [build, ...args], { encoding: "utf8" });
  return { status: r.status, stdout: r.stdout, stderr: r.stderr };
}

const run = (...args: string[]) => runTool(BUILD, ...args);

function withDir(fn: (dir: string) => void, dir = writeBlueprint(baseBlueprint())): void {
  try {
    fn(dir);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

