// The tool copied into a project: tool/ and references/ side by side, node_modules installed there by npm ci.

/** Copies tool/ without node_modules, and references/ next to it unless told not to. */
function copyTool(dir: string, withReferences: boolean): string {
  const tool = join(dir, "tool");
  cpSync(TOOL_DIR, tool, { recursive: true, filter: (src) => src !== join(TOOL_DIR, "node_modules") });
  if (withReferences) cpSync(join(TOOL_DIR, "..", "references"), join(dir, "references"), { recursive: true });
  // A link stands in for `npm ci`: the same lockfile versions, and the test stays offline.
  symlinkSync(join(TOOL_DIR, "node_modules"), join(tool, "node_modules"));
  return join(tool, "build.ts");
}

