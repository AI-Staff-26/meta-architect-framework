// Writes and deletes stay where they belong: nothing through a symlink, no output path outside the blueprint's parent.

/** A scratch directory with one file the build must leave alone. */
function victimDir(rel: string): string {
  const victim = mkdtempSync(join(tmpdir(), "lb-victim-"));
  mkdirSync(join(victim, rel, ".."), { recursive: true });
  writeFileSync(join(victim, rel), "owner data");
  return victim;
}

test("a symlinked agent/prompts is refused: exit 1, nothing deleted or written, its target untouched", () => {
  // agent/prompts is the case the review found; agent/ itself and a single output file are the same hole.
  const cases = [
    { link: "agent/prompts", keep: "keep.md", target: (victim: string) => victim },
    { link: "agent", keep: "prompts/keep.md", target: (victim: string) => victim },
    { link: "agent/SPEC.md", keep: "SPEC.md", target: (victim: string) => join(victim, "SPEC.md") },
  ];
  for (const { link, keep, target } of cases) {
    withDir((dir) => {
      assert.equal(run(dir).status, 0);
      const victim = victimDir(keep);
      try {
        rmSync(join(dir, link), { recursive: true });
        symlinkSync(target(victim), join(dir, link));
        const html = statSync(join(dir, "blueprint.html")).mtimeMs;
        const r = run(dir);
        assert.equal(r.status, 1, `${link}: ${r.stdout}${r.stderr}`);
        assert.match(r.stdout, new RegExp(`^ERROR ${link} is a symlink`, "m"), link);
        assert.match(r.stdout, /errors, 0 warnings — nothing written$/m, link);
        assert.deepEqual(readdirSync(victim, { recursive: true }).sort(), keep.includes("/") ? ["prompts", keep] : [keep], link);
        assert.equal(readFileSync(join(victim, keep), "utf8"), "owner data", link);
        assert.equal(statSync(join(dir, "blueprint.html")).mtimeMs, html, `${link}: blueprint.html was rewritten`);
      } finally {
        rmSync(victim, { recursive: true, force: true });
      }
    });
  }
});

